-- 0014_sandbox_sessions.sql
--
-- The durable ledger for one Alibaba FC Agent Sandbox lifecycle: create,
-- prepare, hibernate, wake, evaluate, kill.
--
-- WHY THIS EXISTS. The sandbox lifecycle is a multi-minute conversation with
-- somebody else's cloud, and the interesting part of it happens while nothing
-- of ours is running: the sandbox sits deep-hibernated — its instance
-- destroyed, its filesystem snapshotted — for as long as training takes
-- elsewhere. Hard rule 3 says nodes are disposable and state is not, and this
-- is the sharpest case of it in the system: if the only record of "there is a
-- live sandbox `i-abc` in ap-southeast-1 that must be woken and then killed"
-- is a Python object in one API process, then a deploy, a crash or an OOM
-- during that wait leaks a sandbox that bills by the second and loses the run
-- with it. These two tables are what make "the API can die mid-hibernation and
-- recover" a true sentence rather than an intention.
--
-- TWO TABLES BECAUSE THEY ANSWER TWO DIFFERENT QUESTIONS. `sandbox_sessions`
-- is the CURRENT truth — one row, mutated by compare-and-set, which is what a
-- reconciler queries and what a controller races on. `sandbox_events` is the
-- HISTORY — append-only, gapless per session, which is what the evidence view
-- renders and what a judge reads. Collapsing them into one table would force
-- the reconciler to reduce the whole history on every sweep, and collapsing
-- them the other way would leave the demo with a state and no story.
--
-- NO TOKEN COLUMN, EVER. The sandbox authenticates to this system as an
-- ordinary machine: `public.machines` already holds a sha256 of its `fmk_`
-- token and hands the raw value out exactly once (0001), and the OSS
-- credentials it needs are presigned URLs minted per object and expiring on
-- their own (spec D5). Adding a token, a key, or a signed URL here would
-- recreate precisely the liability the GitHub App design removes: a table
-- whose leak grants somebody something. See `flashml-cloud/AGENTS.md`,
-- "Nothing stored is a credential". `error_message` is the one free-text
-- column and it is sanitized in the application before it is ever bound —
-- `sandbox_sessions.redact`, which is tested against presigned URLs, `fmk_`
-- tokens, `LTAI` access keys, bearer headers and PEM blocks.
--
-- RLS, AND WHAT "OWNER-SCOPED" MEANS HERE. Row Level Security is enabled on
-- both tables and DELIBERATELY has no policies at all, exactly as in 0001. In
-- Postgres, RLS with zero policies denies every role except the table owner
-- and BYPASSRLS (the `service_role` key this API uses), which is the whole
-- design: the database is API-only and the owner filter is folded into the
-- query itself, never applied afterwards in Python. `fetch_session_for_owner`
-- returns None both for a session that does not exist and for one belonging to
-- somebody else, and the route answers 404 to both — a 403 for "exists but not
-- yours" confirms to a guesser that the id is real. Same doctrine as
-- `fetch_pool_for_member` and `fetch_machine_for_owner`. Do not add a policy
-- naming `anon` or `authenticated` here; `test_no_migration_creates_any_policy_at_all`
-- forbids any policy at all, and that test is the doctrine.
--
-- HOW THIS IS APPLIED: by the migration runner,
-- `python -m flashml_cloud_api.migrate`, which records it in
-- public.schema_migrations. There are two databases, dev (auto-migrated on
-- merge to `develop`) and production (gated behind a manual workflow).
-- Project refs deliberately not named here: they belong in the gitignored env
-- files and in Render's `sync: false` prompts, nowhere in git.
--
-- Do not edit this file after it has been applied anywhere: the runner
-- checksums it, and an edit reads as drift and blocks every later migration.

-- ---------------------------------------------------------------------------
-- sandbox_sessions: one row per sandbox lifecycle, mutated by compare-and-set.
-- ---------------------------------------------------------------------------
create table if not exists public.sandbox_sessions (
    id                  uuid primary key default gen_random_uuid(),

    -- `public.profiles`, not `auth.users`, for two reasons. Every other table
    -- in this schema references profiles and none references auth.users —
    -- 0009 states outright that auth.users is Supabase's schema and is
    -- deliberately untouched — and profiles.id already references
    -- auth.users(id) on delete cascade (0001), so the guarantee is identical.
    -- The cascade is the second reason: a foreign key pointing INTO Supabase's
    -- schema with no action would make Supabase's own user-delete fail on our
    -- table, which is an outage in somebody else's product caused by ours.
    owner_id            uuid not null
                        references public.profiles(id) on delete cascade,

    -- The dedicated pool the sandbox machine serves (spec D3: exactly one
    -- machine in it, so no public task can claim the sandbox and no evaluation
    -- task can escape to another host). Cascades like every other child of
    -- `pools` — pool_members, machine_pools and pool_invites all do — so a
    -- deleted workspace does not leave this table as the one object that
    -- blocks the delete.
    pool_id             uuid not null
                        references public.pools(id) on delete cascade,

    -- NULL until the sandbox has been provisioned and enrolled. `set null`,
    -- not `cascade`: a session whose machine row was deleted still holds a
    -- live `external_sandbox_id` that must be woken and killed, and cascading
    -- would delete the only record that says so — turning a lost pointer into
    -- a leaked, billing sandbox nobody can find.
    machine_id          uuid references public.machines(id) on delete set null,

    -- Plain text with no foreign key, matching `attempts.job_id`,
    -- `contributions.job_id` and `verifications.job_id`. Those columns are
    -- text-without-FK on purpose: a job id here may name a row in
    -- `public.jobs` or a coordinator-side job, and a foreign key would refuse
    -- the second kind at exactly the moment there is nothing to be done
    -- about it.
    training_job_id     text not null,
    evaluation_job_id   text,

    provider            text not null default 'alibaba-fc-sandbox',
    region              text not null,
    template            text not null,

    -- The provider's id for the sandbox. UNIQUE because it is the recovery
    -- key: `unfinished_sessions` hands it to a reconciler, and two sessions
    -- claiming one sandbox would have them fight over whether to wake it or
    -- kill it. NULL until `create` has been observed to succeed — and the gap
    -- between "we asked for a sandbox" and "we know its id" is exactly the
    -- window `REQUESTED` exists to name.
    external_sandbox_id text unique,

    -- Constrained in the database so an invalid state cannot be written even
    -- by a bug in the API, same discipline as `machines.status` (0001). The
    -- legal TRANSITIONS between these are policy and live in
    -- `sandbox_sessions.py` as pure functions, because a state machine
    -- expressed in a trigger cannot be read, argued with, or tested without a
    -- database.
    state               text not null
                        check (state in ('REQUESTED', 'ACTIVE', 'PREPARED',
                                         'HIBERNATED', 'RESUMING', 'EVALUATING',
                                         'SUCCEEDED', 'FAILED', 'TERMINATED')),

    -- sha256 of the marker file written into the sandbox before hibernation
    -- and re-read after the wake. It is the evidence for the only continuity
    -- claim this design is allowed to make: the ENVIRONMENT survived. The
    -- process did not — deep hibernation destroys the instance — and no
    -- column here should ever be read as saying otherwise (spec D2).
    marker_sha256       text,

    -- The capability that powers the PUBLIC, no-auth evidence view. Nullable
    -- so a session's share view can be withdrawn by setting it to NULL, and
    -- UNIQUE so one token names one session. Generated by the APPLICATION
    -- (`sandbox_sessions.new_share_token`, 256 bits from `secrets`), never
    -- here: `gen_random_uuid()` as a default would make the one unauthenticated
    -- surface in this system guessable from a timestamp and a MAC address on
    -- any deployment whose uuid generation is not what we assume.
    share_token         text unique,

    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now(),
    terminated_at       timestamptz,

    -- Sanitized before it is bound, never raw. See the header.
    error_code          text,
    error_message       text
);

