    'keys, bearer headers, JWTs and PEM blocks. A provider SDK''s exception '
    'text routinely echoes the request that caused it.';

alter table public.sandbox_sessions enable row level security;

-- The reconciler's query, and the reason this table exists: every session
-- that owns a live sandbox and has not been terminated. PARTIAL, because the
-- answer is almost always the empty set on a table that only grows — an
-- unpartitioned index would be read in full to find nothing.
--
-- The predicate hardcodes 'TERMINATED' where the Python constant
-- TERMINAL_STATES says the same thing, and those two CAN drift. They are
-- pinned together by
-- test_sandbox_sessions.py::test_the_cleanup_index_predicate_matches_the_policy,
-- which is the only thing standing between a widened terminal set and a
-- reconciler that silently stops sweeping.
create index if not exists sandbox_sessions_unfinished_idx
    on public.sandbox_sessions (created_at)
 where external_sandbox_id is not null
   and state <> 'TERMINATED';

-- "Which sessions belong to this training job" — the submit route's
-- duplicate check and the job page's lookup.
create index if not exists sandbox_sessions_training_job_idx
    on public.sandbox_sessions (training_job_id);

-- Owner-scoped listing, newest first, matching machines_owner_id_idx /
-- jobs_owner_id_idx / cli_credentials_owner_idx. Every owner-scoped read in
-- this schema has one; a session list that sequential-scans is the same bug
-- those indexes exist to prevent.
create index if not exists sandbox_sessions_owner_idx
    on public.sandbox_sessions (owner_id, created_at desc);

-- ---------------------------------------------------------------------------
-- sandbox_events: APPEND ONLY. Nothing updates or deletes a row here.
-- ---------------------------------------------------------------------------
create table if not exists public.sandbox_events (
    id          bigserial primary key,
    session_id  uuid not null
                references public.sandbox_sessions(id) on delete cascade,

    -- Gapless from 1 per session, allocated server-side under the session
    -- row's lock. A client-chosen sequence would let a retry write a second
    -- row for one observation; a bare timestamp ordering would tie on the
    -- sub-millisecond pairs this lifecycle produces (pause is observed and
    -- recorded in the same breath) and render the story out of order.
    sequence    bigint not null check (sequence > 0),

    type        text not null,

    -- WHO SAW IT, which is the difference between evidence and assertion.
    -- 'fc' is the provider's own answer, 'runtime' is the coordinator or the
    -- agent, 'controller' is this API's observation of its own actions. A
    -- reader tracing a disputed latency needs to know which of the three is
    -- speaking; constrained so a fourth cannot appear without this list
    -- being reconsidered.
    source      text not null check (source in ('controller', 'fc', 'runtime')),

    observed_at timestamptz not null default now(),

    -- Measured, not derived. NULL when nothing was timed — an absent
    -- measurement must not read as an instantaneous one, which is what a
    -- `not null default 0` would say about every event that never held a
    -- stopwatch.
    latency_ms  double precision,

    -- `not null default '{}'` so every event answers "what else did you see?"
    -- rather than making readers distinguish two kinds of nothing, matching
    -- verifications.detail and job_rounds.clipped. Sanitized on the way in by
    -- the same redaction the error columns use.
    data        jsonb not null default '{}'::jsonb,

    -- Idempotency as a property of the TABLE, not of the caller's discipline
    -- — the same argument 0003 makes for the credit ledger. A controller that
    -- retries an append after a failed round trip must produce one row, and
    -- with this constraint it can insert with `on conflict do nothing` and be
    -- correct under retry.
    unique (session_id, sequence)
);

comment on table public.sandbox_events is
    'Append-only history of one sandbox session: what was OBSERVED, when, by '
    'whom, and how long it took. Nothing updates or deletes a row here. This '
    'is the P1 evidence for the lifecycle claims — the demo''s wake latency '
    'is read out of this table, not asserted in a slide.';

comment on column public.sandbox_events.sequence is
    'Gapless from 1 per session, allocated server-side under the session '
    'row''s lock. Unique with session_id, which is what makes a retried '
    'append one row instead of two.';

comment on column public.sandbox_events.source is
    'Who observed it: ''fc'' the provider, ''runtime'' the coordinator or '
    'agent, ''controller'' this API. Recorded because a latency the provider '
    'reports and one we timed around the provider are different claims.';

alter table public.sandbox_events enable row level security;

-- NO INDEX ON (session_id, sequence), deliberately — the `unique (session_id,
-- sequence)` constraint above is already backed by exactly that btree, and it
-- serves both the per-session read and its ordering. Adding a second would
-- double the write cost of an append-only table to buy nothing, which is the
-- same call 0010 and 0011 made and wrote down. Pinned by
-- test_sandbox_sessions.py::test_events_are_indexed_by_session_and_sequence,
-- which asserts the INDEX exists rather than how it got there.
--
-- Events are never queried by anything but their session, so there is no
-- second index here at all.
